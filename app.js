function t(key){
  return (translations[currentLanguage] && translations[currentLanguage][key]) || translations.en[key] || key;
}

function updateStaticTexts(){
  const taglineText = document.getElementById("taglineText");
  const startBtn = document.getElementById("startBtn");
  const aboutBtn = document.getElementById("aboutBtn");
  const disclaimerText = document.getElementById("disclaimerText");
  const footerText = document.getElementById("footerText");
  const installBtn = document.getElementById("installBtn");

  if(taglineText) taglineText.textContent = t("tagline");
  if(startBtn) startBtn.textContent = t("startCheck");
  if(aboutBtn) aboutBtn.textContent = t("about");
  if(disclaimerText) disclaimerText.textContent = t("disclaimer");
  if(footerText) footerText.textContent = t("footer");
  if(installBtn) installBtn.textContent = t("install");

  document.querySelectorAll(".lang-btn").forEach(btn => btn.classList.remove("active"));
  const activeBtn = document.getElementById(`lang-${currentLanguage}`);
  if(activeBtn) activeBtn.classList.add("active");
}

function setLanguage(lang){
  currentLanguage = lang;
  localStorage.setItem("carebridgeLanguage", lang);
  updateStaticTexts();
  rerenderCurrentView();
}

function rerenderCurrentView(){
  switch(currentView.screen){
    case "age":
      selectAgeGroup();
      break;
    case "symptoms":
      showSymptomCategories();
      break;
    case "fever1":
      fever();
      break;
    case "fever2":
      feverStep2(currentView.data.highFever);
      break;
    case "dental1":
      dental();
      break;
    case "dental2":
      dentalStep2(currentView.data.severe);
      break;
    case "stomach1":
      stomach();
      break;
    case "stomach2":
      stomachStep2(currentView.data.severe);
      break;
    case "snake":
      snakeBite();
      break;
    case "result":
      showResult(currentView.data.level);
      break;
    case "about":
      showAbout();
      break;
    default:
      document.getElementById("app").innerHTML = "";
      currentView = { screen: "home" };
  }
}

document.addEventListener("DOMContentLoaded", () => {
  updateStaticTexts();
  updateInstallButton();
});

/* ===================== PWA INSTALL ===================== */

window.addEventListener("beforeinstallprompt", (e) => {
  e.preventDefault();
  deferredPrompt = e;
  updateInstallButton();
});

window.addEventListener("appinstalled", () => {
  deferredPrompt = null;
  updateInstallButton();
});

function updateInstallButton(){
  const installBtn = document.getElementById("installBtn");

  if(!installBtn) return;

  if(deferredPrompt){
    installBtn.style.display = "block";
    installBtn.onclick = installCareBridge;
  } else {
    installBtn.style.display = "none";
    installBtn.onclick = null;
  }
}

async function installCareBridge(){
  if(!deferredPrompt) return;

  deferredPrompt.prompt();
  await deferredPrompt.userChoice;
  deferredPrompt = null;
  updateInstallButton();
}

