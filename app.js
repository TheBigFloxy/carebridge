function filterSymptoms(){
  const input = document.getElementById("searchSymptoms").value.toLowerCase().trim();

  const symptomMap = [
    {
      id: 0,
      keywords: ["fever", "malaria", "temperature", "hot body", "hot", "chills", "sweating", "body hot", "zazzabi", "iba", "aru oku", "ọkụ", "oku"]
    },
    {
      id: 1,
      keywords: ["dental", "tooth", "teeth", "gum", "gums", "mouth", "swelling", "toothache", "tooth pain", "mouth pain", "hakori", "eyin", "eze"]
    },
    {
      id: 2,
      keywords: ["stomach", "belly", "vomit", "vomiting", "abdominal", "abdomen", "pain", "nausea", "stomach ache", "belly pain", "ciki", "inu", "afo"]
    },
    {
      id: 3,
      keywords: ["snake", "snake bite", "snakebite", "bite", "venom", "fang", "maciji", "ejo", "ejò", "agwo", "agwọ"]
    }
  ];

  const buttons = document.querySelectorAll("#symptomList button");
  let visibleCount = 0;

  buttons.forEach((button, index) => {
    const buttonText = button.innerText.toLowerCase();

    const matchedGroup = symptomMap.find(item => item.id === index);
    const matchesText = buttonText.includes(input);
    const matchesKeyword = matchedGroup
      ? matchedGroup.keywords.some(keyword => keyword.includes(input) || input.includes(keyword))
      : false;

    if(input === "" || matchesText || matchesKeyword){
      button.style.display = "block";
      visibleCount++;
    } else {
      button.style.display = "none";
    }
  });

  const noResults = document.getElementById("noResults");
  if(noResults){
    noResults.style.display = visibleCount === 0 ? "block" : "none";
  }
}

